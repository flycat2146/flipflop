use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    // Plain Fluent (not a -light/-dark variant) so the std-widgets can switch
    // color scheme at runtime along with `Theme` (see the Appearance setting).
    let config = slint_build::CompilerConfiguration::new()
        .with_style("fluent".into())
        // translations/<lang>/LC_MESSAGES/flipflop.po, compiled into the binary
        // (no files to ship next to the APK).
        .with_bundled_translations("translations")
        // A flat msgid catalog with no per-component msgctxt, shared with the
        // generated table src/i18n.rs uses for the strings Rust formats itself.
        .with_default_translation_context(slint_build::DefaultTranslationContext::None);
    slint_build::compile_with_config("src/ui/app-window.slint", config)
        .expect("failed to compile Slint UI");

    build_translation_table();

    if std::env::var("TARGET")
        .unwrap_or_default()
        .contains("android")
    {
        build_java_helpers();
    }

    #[cfg(windows)]
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        embed_windows_icon();
    }
}

/// Slint's bundled translations only cover `@tr(...)` in `.slint` files; the strings
/// Rust formats itself (transfer statuses, toasts, history rows, …) need the same
/// catalogs at runtime, which is what this table is for. See src/i18n.rs.
fn build_translation_table() {
    use rspolib::TranslatedEntry;

    let translations = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("translations");
    println!("cargo:rerun-if-changed={}", translations.display());

    let mut languages: Vec<String> = Vec::new();
    let mut catalogs: Vec<Vec<(String, Vec<String>)>> = Vec::new();

    let mut dirs: Vec<PathBuf> = std::fs::read_dir(&translations)
        .map(|entries| entries.flatten().map(|e| e.path()).collect())
        .unwrap_or_default();
    // The Slint compiler sorts the directories too; keep the same order so a
    // language index means the same thing on both sides.
    dirs.sort();
    for dir in dirs {
        let po = dir.join("LC_MESSAGES").join("flipflop.po");
        if !po.is_file() {
            continue;
        }
        let language = dir
            .file_name()
            .expect("translation dir name")
            .to_string_lossy()
            .into_owned();
        let catalog = rspolib::pofile(po.as_path())
            .unwrap_or_else(|e| panic!("parsing {}: {e}", po.display()));

        let mut messages = Vec::new();
        for entry in &catalog.entries {
            // The header entry has an empty msgid; contexts are unused here.
            if entry.msgid.is_empty() || entry.msgctxt.is_some() || !entry.translated() {
                continue;
            }
            let forms: Vec<String> = if entry.msgstr_plural.is_empty() {
                entry.msgstr.iter().cloned().collect()
            } else {
                entry.msgstr_plural.clone()
            };
            if forms.is_empty() {
                continue;
            }
            messages.push((entry.msgid.clone(), forms));
        }
        messages.sort();
        languages.push(language);
        catalogs.push(messages);
    }

    let mut out = String::from(
        "// @generated by build.rs from translations/*/LC_MESSAGES/flipflop.po; do not edit.\n\n",
    );
    out.push_str("/// Bundled language codes, in the same order the Slint compiler uses.\n");
    out.push_str("pub static LANGUAGES: &[&str] = &[");
    for language in &languages {
        let _ = write!(out, "{}, ", literal(language));
    }
    out.push_str("];\n\n");

    for (index, messages) in catalogs.iter().enumerate() {
        out.push_str("static TABLE_");
        let _ = write!(out, "{index}");
        out.push_str(": &[(&str, &[&str])] = &[\n");
        for (msgid, forms) in messages {
            let _ = write!(out, "    ({}, &[", literal(msgid));
            for form in forms {
                let _ = write!(out, "{}, ", literal(form));
            }
            out.push_str("]),\n");
        }
        out.push_str("];\n\n");
    }

    out.push_str("/// One table per `LANGUAGES[i]`; sorted by msgid for binary search.\n");
    out.push_str("pub static TABLES: &[&[(&str, &[&str])]] = &[");
    for index in 0..catalogs.len() {
        let _ = write!(out, "TABLE_{index}, ");
    }
    out.push_str("];\n");

    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR"));
    std::fs::write(out_dir.join("i18n_table.rs"), out).expect("writing the translation table");
}

/// A Rust string literal for `value`, `\n` and friends escaped.
fn literal(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                let _ = write!(out, "\\u{{{:x}}}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Give flipflop.exe its icon in Explorer, the taskbar and the installer's
/// shortcuts. Version info comes from Cargo.toml.
#[cfg(windows)]
fn embed_windows_icon() {
    println!("cargo:rerun-if-changed=windows/flipflop.ico");
    winresource::WindowsResource::new()
        .set_icon("windows/flipflop.ico")
        .compile()
        .expect("failed to embed Windows resources");
}

/// Compile `src/android/java` into `$OUT_DIR/classes.dex`, which src/android.rs
/// embeds and loads at runtime (cargo-apk packages no Java code itself).
/// Same toolchain as Slint's own Android helper: javac + d8 from the SDK.
fn build_java_helpers() {
    use android_build::{Dexer, JavaBuild};

    let sources = [
        "src/android/java/com/flipflop/app/FilePicker.java",
        "src/android/java/com/flipflop/app/BluetoothLink.java",
        "src/android/java/com/flipflop/app/NetworkWatch.java",
        "src/android/java/com/flipflop/app/Storage.java",
        "src/android/java/com/flipflop/app/QrCamera.java",
        "src/android/java/com/flipflop/app/AppList.java",
    ];
    for src in sources {
        println!("cargo:rerun-if-changed={src}");
    }
    let release = std::env::var("PROFILE").as_deref() == Ok("release");
    let out_dir: PathBuf = std::env::var_os("OUT_DIR").unwrap().into();
    let classes = out_dir.join("java");
    let _ = std::fs::remove_dir_all(&classes);
    std::fs::create_dir_all(&classes).expect("create java output dir");
    let android_jar = android_build::android_jar(None).expect("no Android platform found");

    let javac = JavaBuild::new()
        .files(sources)
        .class_path(&android_jar)
        .classes_out_dir(&classes)
        .java_source_version(8)
        .java_target_version(8)
        .command()
        .expect("javac command")
        .args(["-encoding", "UTF-8", "-Xlint:-options"])
        .output()
        .expect("run javac");
    assert!(
        javac.status.success(),
        "javac failed: {}",
        String::from_utf8_lossy(&javac.stderr)
    );

    let d8 = Dexer::new()
        .android_jar(&android_jar)
        .class_path(&classes)
        .collect_classes(&classes)
        .expect("collect classes")
        .release(release)
        .android_min_api(26)
        .out_dir(out_dir)
        .command()
        .expect("d8 command")
        .output()
        .expect("run d8");
    assert!(
        d8.status.success(),
        "d8 failed: {}",
        String::from_utf8_lossy(&d8.stderr)
    );
}
